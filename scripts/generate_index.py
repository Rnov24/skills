#!/usr/bin/env python3
"""Generate docs/SKILL_INDEX.md and skills-index.json from skill frontmatter.

The index is a build artifact. Never edit it by hand; edit the SKILL.md
frontmatter (name, description, phase, keywords) and re-run this script.
The router skill depends on the index matching the folders; validation
fails when they drift.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

def parse_frontmatter(text):
    m = re.match(r'^---\n(.*?)\n---\n', text, re.S)
    if not m:
        return {}
    fm = {}
    for line in m.group(1).splitlines():
        if ':' in line:
            k, v = line.split(':', 1)
            fm[k.strip()] = v.strip()
    return fm

def collect():
    skills = []
    for d in sorted((ROOT / 'skills').iterdir()):
        f = d / 'SKILL.md'
        if not f.exists():
            continue
        fm = parse_frontmatter(f.read_text(encoding='utf-8'))
        skills.append({
            'name': fm.get('name', d.name),
            'phase': fm.get('phase', 'unclassified'),
            'description': fm.get('description', ''),
            'keywords': [k.strip() for k in fm.get('keywords', '').split(',') if k.strip()],
            'slash_only': fm.get('disable-model-invocation') == 'true',
            'path': f'skills/{d.name}/SKILL.md',
        })
    return skills

def main():
    skills = collect()
    (ROOT / 'skills-index.json').write_text(json.dumps(skills, indent=1, ensure_ascii=False) + '\n')
    lines = [
        '# Skill index',
        '',
        'Generated by `scripts/generate_index.py` from skill frontmatter.',
        'Do not edit by hand. Agents: search this table (or run',
        '`scripts/find_skill.py "<task words>"`) before opening any SKILL.md.',
        '',
        '| Skill | Phase | Use when | Keywords |',
        '|---|---|---|---|',
    ]
    for s in skills:
        desc = s['description'].replace('|', '/')
        kw = ', '.join(s['keywords'])
        slash = ' (slash only)' if s['slash_only'] else ''
        lines.append(f"| `{s['name']}`{slash} | {s['phase']} | {desc} | {kw} |")
    lines.append('')
    lines.append(f"{len(skills)} skills indexed.")
    (ROOT / 'docs' / 'SKILL_INDEX.md').write_text('\n'.join(lines) + '\n')
    print(f"indexed {len(skills)} skills -> docs/SKILL_INDEX.md, skills-index.json")

if __name__ == '__main__':
    sys.exit(main())
